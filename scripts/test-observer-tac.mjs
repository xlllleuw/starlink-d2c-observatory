import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../public/js/app.js',import.meta.url),'utf8');
const extract=name=>source.slice(source.indexOf(`function ${name}(`),source.indexOf('\nfunction ',source.indexOf(`function ${name}(`)+1));
const elements=new Map();const $=id=>{if(!elements.has(id))elements.set(id,{checked:true,value:'',textContent:''});return elements.get(id);};
let cleared=0,center;
const state={observerSelected:true,lat:40,lon:-90,tacId:123,tacReady:true,countryTacs:{},tacCountryId:null};
const stop=new Error('Stop before geometry construction');
const context=vm.createContext({state,$,lastTacFocus:'old',tacLayer:{entities:{removeAll(){cleared++;}}},tacOutlines:{removeAll(){cleared++;}},viewer:{scene:{requestRender(){}}},observerEntity:{show:true},renderSky(){},updatePositions(){},renderDetail(){},nearbyTacs(lat,lon){center=[lat,lon];throw stop;}});
vm.runInContext(extract('refreshTac')+'\n'+extract('clearObserver'),context);
assert.throws(()=>vm.runInContext('refreshTac({lat:0,lon:0})',context),e=>e===stop);
assert.deepEqual(center,[40,-90]);
vm.runInContext('clearObserver()',context);
assert.equal(state.observerSelected,false);assert.equal(state.tacId,null);
assert.equal($('layer-tac').checked,true);assert.equal(context.observerEntity.show,false);
assert.ok(cleared>=4);
center=null;vm.runInContext('refreshTac()',context);assert.equal(center,null);
$('layer-tac').checked=false;vm.runInContext('refreshTac()',context);
$('layer-tac').checked=true;vm.runInContext('refreshTac()',context);assert.equal(center,null);
assert.ok(!source.includes('viewer.camera.moveEnd.addEventListener'));
console.log('PASS: local TAC stays at observer coordinates; deselection preserves toggle and prevents grid reappearance.');
